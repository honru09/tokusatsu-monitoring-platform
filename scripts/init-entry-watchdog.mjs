import { readFile, mkdir, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { resolve, dirname, join, isAbsolute, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { validTunnelUrl } from "./entry-watchdog-core.mjs";
const run = promisify(execFile), root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const privateDir = join(root, ".private-entry");
await mkdir(privateDir, { recursive: true });
const pid = Number(process.argv[2]);
if (!Number.isSafeInteger(pid) || pid < 1) throw new Error("Pass the verified existing tunnel PID");
const { stdout } = await run("powershell.exe", ["-NoProfile", "-NonInteractive", "-Command", `$p=Get-CimInstance Win32_Process -Filter 'ProcessId=${pid}'; if($p){[pscustomobject]@{pid=$p.ProcessId;name=$p.Name;path=$p.ExecutablePath;command=$p.CommandLine;created=$p.CreationDate.ToUniversalTime().ToString('o')}|ConvertTo-Json -Compress}`], { windowsHide: true, timeout: 15_000 });
const info = JSON.parse(stdout);
if (info.name?.toLowerCase() !== "cloudflared.exe" || !info.command.includes("--url http://localhost:3000")) throw new Error("Not this project's local tunnel");
const logPath = info.command.match(/--logfile\s+(?:"([^"]+)"|(\S+))/)?.slice(1).find(Boolean);
if (!logPath || !isAbsolute(logPath) || relative(root, logPath).startsWith("..")) throw new Error("Tunnel log must be inside this workspace");
const log = await readFile(logPath, "utf8");
const url = (log.match(/https:\/\/[a-z0-9-]+\.trycloudflare\.com/g) ?? []).at(-1);
if (!validTunnelUrl(url)) throw new Error("No valid current URL in selected tunnel log");
const state = { pid: info.pid, created: info.created, logPath, generation: Date.now(), url };
await writeFile(join(privateDir, "config.json"), JSON.stringify({ cloudflared: info.path, entryOrigin: null }), { mode: 0o600, flag: "wx" });
await writeFile(join(privateDir, "tunnel.json"), JSON.stringify(state), { mode: 0o600, flag: "wx" });
console.log(`Adopted existing tunnel without restart: ${url}`);
